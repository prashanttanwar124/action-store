<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\QueryException;
use Illuminate\Database\UniqueConstraintViolationException;

class Supplier extends Model
{
    use HasFactory;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'name',
        'code',
        'contact_person',
        'email',
        'phone',
        'address',
        'city',
        'state',
        'country',
        'postal_code',
        'lead_time_days',
        'payment_terms',
        'status',
        'notes',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'lead_time_days' => 'integer',
        ];
    }

    /**
     * Track whether the code was automatically generated on creation.
     */
    public bool $wasCodeAutoGenerated = false;

    /**
     * Automatically generate unique supplier code if not provided.
     */
    protected static function booted(): void
    {
        static::creating(function (Supplier $supplier) {
            if (empty($supplier->code)) {
                $supplier->code = static::generateUniqueCode();
                $supplier->wasCodeAutoGenerated = true;
            }
        });
    }

    /**
     * Generate the next unique supplier code (e.g. SUP-001, SUP-002), hardened against collisions.
     */
    public static function generateUniqueCode(): string
    {
        $maxId = (int) (static::max('id') ?? 0);

        $latestSupplier = static::query()
            ->where('code', 'like', 'SUP-%')
            ->orderByRaw('LENGTH(code) DESC, code DESC')
            ->get(['code'])
            ->first(fn ($s) => preg_match('/^SUP-(\d+)$/', (string) $s->code));

        $maxCodeNumber = 0;
        if ($latestSupplier && preg_match('/^SUP-(\d+)$/', (string) $latestSupplier->code, $matches)) {
            $maxCodeNumber = (int) $matches[1];
        }

        $nextNumber = max($maxId, $maxCodeNumber) + 1;

        do {
            $candidate = 'SUP-'.str_pad((string) $nextNumber, 3, '0', STR_PAD_LEFT);
            $nextNumber++;
        } while (static::where('code', $candidate)->exists());

        return $candidate;
    }

    /**
     * Save the model to the database with automatic retry on auto-generated code collisions.
     *
     * @param  array<string, mixed>  $options
     */
    public function save(array $options = []): bool
    {
        $attempts = 0;
        $maxAttempts = 5;

        while (true) {
            try {
                return parent::save($options);
            } catch (UniqueConstraintViolationException|QueryException $e) {
                $attempts++;
                $isCodeCollision = str_contains($e->getMessage(), 'suppliers_code_unique')
                    || str_contains($e->getMessage(), 'suppliers.code')
                    || str_contains($e->getMessage(), 'code');

                if (! $this->exists && $this->wasCodeAutoGenerated && $isCodeCollision && $attempts < $maxAttempts) {
                    $this->code = static::generateUniqueCode();

                    continue;
                }

                throw $e;
            }
        }
    }

    /**
     * Products supplied by this supplier.
     *
     * @return HasMany<Product, $this>
     */
    public function products(): HasMany
    {
        return $this->hasMany(Product::class);
    }
}
