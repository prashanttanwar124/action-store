    /**
     * MED-05: Stress-test supplier code generation against sequence gaps, high numbers, and custom strings.
     */
    public function test_supplier_code_generation_handles_gaps_and_high_sequences(): void
    {
        // Gaps: SUP-001 and SUP-005 exist
        $s1 = Supplier::create(['name' => 'Supplier 1']);
        $this->assertEquals('SUP-001', $s1->code);

        $s5 = Supplier::create(['name' => 'Supplier 5', 'code' => 'SUP-005']);
        $this->assertEquals('SUP-005', $s5->code);

        $sNext = Supplier::create(['name' => 'Supplier 6']);
        $this->assertEquals('SUP-006', $sNext->code);

        // Pre-populated high code SUP-999
        $s999 = Supplier::create(['name' => 'Supplier 999', 'code' => 'SUP-999']);
        $this->assertEquals('SUP-999', $s999->code);

        // Next auto-generated must cross into 4-digit sequence SUP-1000
        $s1000 = Supplier::create(['name' => 'Supplier 1000']);
        $this->assertEquals('SUP-1000', $s1000->code);

        $s1001 = Supplier::create(['name' => 'Supplier 1001']);
        $this->assertEquals('SUP-1001', $s1001->code);

        // Long custom non-numeric codes should not corrupt regex matching
        Supplier::create(['name' => 'Long Code Vendor', 'code' => 'SUP-EXTREMELY-LONG-CUSTOM-VENDOR-KEY']);
        $s1002 = Supplier::create(['name' => 'Supplier 1002']);
        $this->assertEquals('SUP-1002', $s1002->code);
    }

    /**
     * MED-05: Stress-test collision retry logic when a race condition occurs.
     */
    public function test_supplier_code_generation_retries_on_race_condition_collision(): void
    {
        // Simulate candidate generation in thread A
        $supplierThreadA = new Supplier(['name' => 'Thread A Supplier']);
        $supplierThreadA->code = 'SUP-555';
        $supplierThreadA->wasCodeAutoGenerated = true;

        // Thread B successfully commits SUP-555 first
        Supplier::create(['name' => 'Thread B Supplier', 'code' => 'SUP-555']);

        // Thread A calls save(); should intercept UniqueConstraintViolationException and auto-increment
        $saved = $supplierThreadA->save();

        $this->assertTrue($saved);
        $this->assertEquals('SUP-556', $supplierThreadA->code);
        $this->assertDatabaseHas('suppliers', ['id' => $supplierThreadA->id, 'code' => 'SUP-556']);
    }

    /**
     * MED-13: Stress-test customer recent orders query starvation.
     * Customer A with 100 orders, Customer B with 3 orders, Customer C with 1 order.
     */
    public function test_admin_customer_recent_orders_query_does_not_starve_low_volume_customers(): void
    {
        $admin = Admin::where('email', 'admin@masalamart.com')->first();

        // Customer B and C created with earlier orders
        $customerB = User::factory()->create(['name' => 'Customer B', 'created_at' => now()->subMinutes(10)]);
        for ($i = 0; $i < 3; $i++) {
            Order::factory()->create([
                'user_id' => $customerB->id,
                'customer_name' => $customerB->name,
                'customer_email' => $customerB->email,
                'created_at' => now()->subHours(2)->addMinutes($i),
            ]);
        }

        $customerC = User::factory()->create(['name' => 'Customer C', 'created_at' => now()->subMinutes(15)]);
        Order::factory()->create([
            'user_id' => $customerC->id,
            'customer_name' => $customerC->name,
            'customer_email' => $customerC->email,
            'created_at' => now()->subHours(3),
        ]);

        // Customer A with 100 newer orders (worst-case for starvation)
        $customerA = User::factory()->create(['name' => 'Customer A', 'created_at' => now()->subMinutes(5)]);
        for ($i = 0; $i < 100; $i++) {
            Order::factory()->create([
                'user_id' => $customerA->id,
                'customer_name' => $customerA->name,
                'customer_email' => $customerA->email,
                'created_at' => now()->subMinutes(100 - $i),
            ]);
        }

        $response = $this->actingAs($admin, 'admin')->get(route('admin.customers.index'));

        $response->assertStatus(200);
        $response->assertInertia(function (Assert $page) use ($customerA, $customerB, $customerC) {
            $page->component('Admin/Customers/Index');

            $props = $page->toArray()['props'];
            $customers = collect($props['customers']['data']);

            $cA = $customers->firstWhere('id', $customerA->id);
            $cB = $customers->firstWhere('id', $customerB->id);
            $cC = $customers->firstWhere('id', $customerC->id);

            $this->assertNotNull($cA, 'Customer A must be present in customer list');
            $this->assertNotNull($cB, 'Customer B must be present in customer list');
            $this->assertNotNull($cC, 'Customer C must be present in customer list');

            // Zero starvation verification:
            // Customer A is capped at 5 recent orders
            $this->assertCount(5, $cA['recent_orders']);
            // Customer B receives all 3 of their recent orders
            $this->assertCount(3, $cB['recent_orders']);
            // Customer C receives their 1 recent order
            $this->assertCount(1, $cC['recent_orders']);
        });
    }

    /**
     * HIGH-05: Stress-test permission scoping on store-info and pickup-settings routes.
     */
    public function test_permission_scoping_on_settings_routes(): void
    {
        // Admin with ONLY manage products permission
        $catalogAdmin = Admin::create([
            'name' => 'Catalog Admin',
            'email' => 'catalog@masalamart.com',
            'password' => Hash::make('password123'),
        ]);
        $catalogRole = Role::findOrCreate('Catalog Only', 'admin');
        $catalogRole->syncPermissions(['manage products']);
        $catalogAdmin->assignRole($catalogRole);

        // Must be forbidden (403) for catalog admin
        $this->actingAs($catalogAdmin, 'admin')->get(route('admin.store-info.edit'))->assertStatus(403);
        $this->actingAs($catalogAdmin, 'admin')->put(route('admin.store-info.update'), ['name' => 'Hacked'])->assertStatus(403);
        $this->actingAs($catalogAdmin, 'admin')->post(route('admin.store-info.busy-mode'), ['busy_mode_extra_minutes' => 15])->assertStatus(403);
        $this->actingAs($catalogAdmin, 'admin')->get(route('admin.pickup-settings.edit'))->assertStatus(403);
        $this->actingAs($catalogAdmin, 'admin')->put(route('admin.pickup-settings.update'), ['is_pickup_active' => false])->assertStatus(403);

        // Store Manager (has manage settings) must succeed (200)
        $manager = Admin::create([
            'name' => 'Store Manager User',
            'email' => 'manager_test@masalamart.com',
            'password' => Hash::make('password123'),
        ]);
        $managerRole = Role::findByName('Store Manager', 'admin');
        $manager->assignRole($managerRole);

        $this->actingAs($manager, 'admin')->get(route('admin.store-info.edit'))->assertStatus(200);
        $this->actingAs($manager, 'admin')->get(route('admin.pickup-settings.edit'))->assertStatus(200);
    }

    /**
     * HIGH-02: Stress-test query bounding in validateOrderRequirements().
     */
    public function test_checkout_validation_executes_bounded_queries(): void
    {
        $this->travelTo(now()->setTime(12, 0));

        $products = Product::factory()->count(15)->create(['stock' => 100]);
        $kits = [];
        for ($k = 0; $k < 5; $k++) {
            $kit = RecipeKit::create([
                'name' => "Paneer Kit {$k}",
                'slug' => "paneer-kit-{$k}",
                'price' => 30,
                'is_active' => true,
            ]);
            $kit->products()->attach($products[$k], ['quantity' => 1]);
            $kits[] = $kit;
        }

        $controller = app()->make(OrderController::class);
        $storeInfo = StoreSetting::current();

        $measure = function (int $numItems) use ($controller, $storeInfo, $products, $kits) {
            $items = [];
            for ($i = 0; $i < $numItems; $i++) {
                if ($i % 3 === 0 && isset($kits[$i / 3])) {
                    $kit = $kits[$i / 3];
                    $items[] = ['id' => $kit->slug, 'type' => 'recipe-kit', 'name' => $kit->name, 'price' => 30, 'quantity' => 1];
                } else {
                    $prod = $products[$i % count($products)];
                    $items[] = ['id' => $prod->id, 'name' => $prod->name, 'price' => $prod->price, 'quantity' => 1];
                }
            }

            $validated = [
                'items' => $items,
                'fulfillment_type' => 'Store Pickup',
                'pickup_timing_mode' => 'asap',
            ];

            DB::flushQueryLog();
            DB::enableQueryLog();

            $reflection = new ReflectionClass($controller);
            $method = $reflection->getMethod('validateOrderRequirements');
            $method->setAccessible(true);
            $method->invoke($controller, $validated, $storeInfo);

            $queries = DB::getQueryLog();

            return count($queries);
        };

        $q1 = $measure(1);
        $q5 = $measure(5);
        $q15 = $measure(15);

        // Query count for 15 items must equal query count for 5 items (strictly O(1) query complexity)
        $this->assertEquals($q5, $q15, "Query count for 15 items ($q15) must not exceed query count for 5 items ($q5)");
        $this->assertLessThanOrEqual(4, $q15, 'Query count must be bounded at <= 4 queries');
    }
